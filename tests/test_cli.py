def test_submitted_job_id_survives_a_failure_to_save_the_script(fake_schedulers, capsys, monkeypatch):
    def fail(self, *args, **kwargs):
        raise OSError("disk full")

    monkeypatch.setattr("usub.backends.base.Rendered.save", fail)
    assert main(["r", "-s", "-b", "slurm", "--cwd", str(fake_schedulers), "-o", "logs", "--", "true"]) == 0
    captured = capsys.readouterr()
    assert captured.out == "777\n"
    assert "usub: warning: Job 777 was submitted but its script could not be saved: disk full" in captured.err
