def test_unknown_config_option_warns_on_stderr_but_still_renders(capsys, tmp_path):
    (tmp_path / ".usub.toml").write_text('[defaults]\ntipo = 1\nlsf_mem_unit = "GB"\n')
    assert main(["r", "-b", "slurm", "--cwd", str(tmp_path), "--", "true"]) == 0
    captured = capsys.readouterr()
    assert captured.err.splitlines() == [
        "usub: warning: Unknown option(s) tipo for the slurm backend (it accepts: gpu_args); check for typos"]
    assert "#!/bin/bash" in captured.out  # lsf_mem_unit belongs to another backend, so only tipo is reported

def test_conflicting_output_options_are_refused_before_anything_is_submitted(fake_schedulers, capsys):
    for flags in (["-s", "--emit", "cmd"], ["-s", "--write", str(fake_schedulers / "x.sh")],
                  ["--emit", "cmd", "--write", str(fake_schedulers / "x.sh")]):
        assert main(["r", "-b", "lsf", "--cwd", str(fake_schedulers), "-o", "logs", *flags, "--", "true"]) == 2
        assert "Use only one of --submit, --emit cmd and --write" in capsys.readouterr().err
    assert not (fake_schedulers / "bsub.stdin").exists()

