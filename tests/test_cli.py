def test_config_init_show_path(tmp_path, capsys, monkeypatch):
    path = tmp_path / "cfg" / ".usub.toml"
    monkeypatch.setenv("USUB_CONFIG", str(path))
    assert main(["config", "path"]) == 0
    assert capsys.readouterr().out.strip() == str(path)  # nothing loaded: where init would write
    assert main(["config", "init"]) == 0
    assert "[profiles.lsf]" in path.read_text()
    assert main(["config", "init"]) == 2
    assert main(["config", "path"]) == 0
    assert capsys.readouterr().out.strip().endswith(str(path))
    assert main(["config", "show", "-p", "lsf"]) == 0
    out = capsys.readouterr().out
    assert "profile: lsf" in out and "backend: lsf" in out and "lsf_rusage = True" in out

