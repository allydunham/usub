import os
import stat
from pathlib import Path

import pytest

from usub.cli import main

@pytest.fixture
def fake_schedulers(tmp_path, monkeypatch):
    """bsub/sbatch stand-ins that record their stdin/argv and print a job id."""
    bindir = tmp_path / "bin"
    bindir.mkdir()
    for name, reply in (("bsub", "Job <4242> is submitted to queue <normal>."),
                        ("sbatch", "Submitted batch job 777")):
        script = bindir / name
        script.write_text(f'#!/bin/bash\necho "$@" > "{tmp_path}/{name}.args"\n'
                          f'cat > "{tmp_path}/{name}.stdin"\necho "{reply}"\n')
        script.chmod(script.stat().st_mode | stat.S_IXUSR)
    monkeypatch.setenv("PATH", f"{bindir}{os.pathsep}{os.environ['PATH']}")
    return tmp_path

def test_print_script(capsys, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    assert main(["r", "-b", "lsf", "-m", "2G", "--", "echo", "hi"]) == 0
    out = capsys.readouterr().out
    assert out.startswith("#!/bin/bash\n#BSUB -J echo\n")
    assert out.rstrip().endswith("echo hi")
    assert (Path.home() / "usub_logs").is_dir()  # default logdir; created so a piped submission can log

def test_command_without_separator(capsys, tmp_path):
    assert main(["r", "-b", "slurm", "--cwd", str(tmp_path), "python", "x.py", "-v"]) == 0
    assert capsys.readouterr().out.rstrip().endswith("python x.py -v")

@pytest.mark.parametrize("argv, command", [
    (["-m", "4G", "--", "python", "x.py", "--lr", "0.1"], "python x.py --lr 0.1"),
    (["-m", "4G", "python", "x.py", "-v"], "python x.py -v"),
    (["--", "-weird", "arg"], "-weird arg"),
    (["--", "echo", "-m", "5"], "echo -m 5"),
    (["--", "git", "log", "--", "file"], "git log -- file"),
])
def test_command_separator(argv, command, capsys, tmp_path):
    assert main(["r", "-b", "slurm", "--cwd", str(tmp_path), *argv]) == 0
    out = capsys.readouterr().out
    assert command in out and "--" not in out.split("# generated by")[1].split("cd ")[0]

def test_cmds_file_becomes_an_array(capsys, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "commands.txt").write_text("echo a\necho b\necho c\n")
    assert main(["r", "-b", "lsf", "--cwd", "/", "-C", "commands.txt", "-j", "2"]) == 0
    out = capsys.readouterr().out
    assert '#BSUB -J "commands[1-3]%2"' in out  # named after the file
    assert f'sed -n "${{LSB_JOBINDEX}}p" {tmp_path}/commands.txt | bash' in out  # relative to the shell, not --cwd

def test_file_list_runs_command_per_path(capsys, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "bams.txt").write_text("a.bam\nb.bam\n")
    assert main(["r", "-b", "slurm", "--cwd", "/", "-F", "bams.txt", "-j", "2", "--", "samtools", "index", "{}"]) == 0
    out = capsys.readouterr().out
    assert "#SBATCH --array=1-2%2" in out and "#SBATCH --job-name=samtools" in out
    assert f'f=$(sed -n "${{SLURM_ARRAY_TASK_ID}}p" {tmp_path}/bams.txt); samtools index "$f"' in out

@pytest.mark.parametrize("backend, gpus, directive", [
    ("lsf", "num=2:gmodel=A100", "#BSUB -gpu num=2:gmodel=A100\n"),
    ("lsf", "2", "#BSUB -gpu num=2\n"),
    ("slurm", "a100:2", "#SBATCH --gres=gpu:a100:2\n"),
])
def test_gpu_option_overrides_config(backend, gpus, directive, capsys, tmp_path):
    (tmp_path / ".usub.toml").write_text("[defaults]\ngpus = 1\n")
    assert main(["r", "-b", backend, "--cwd", str(tmp_path), "-g", gpus, "--", "python", "t.py"]) == 0
    out = capsys.readouterr().out
    assert directive in out and "num=1" not in out and "gpu:1" not in out
    assert main(["r", "-b", backend, "--cwd", str(tmp_path), "--", "python", "t.py"]) == 0  # config value
    assert ("num=1" if backend == "lsf" else "gpu:1") in capsys.readouterr().out

def test_write_and_emit_cmd(capsys, tmp_path):
    target = tmp_path / "job.sh"
    assert main(["r", "-b", "lsf", "--cwd", str(tmp_path), "--write", str(target), "--", "true"]) == 0
    assert target.read_text().startswith("#!/bin/bash")
    assert "bsub < " in capsys.readouterr().err
    assert main(["r", "-b", "slurm", "--cwd", str(tmp_path), "--emit", "cmd", "--", "true"]) == 0
    assert capsys.readouterr().out.startswith("sbatch --job-name=true ")

@pytest.mark.parametrize("backend, program, job_id", [("lsf", "bsub", "4242"), ("slurm", "sbatch", "777")])
def test_submit(fake_schedulers, capsys, backend, program, job_id):
    tmp = fake_schedulers
    argv = ["r", "-s", "-b", backend, "--cwd", str(tmp), "-o", "usub-logs", "-a", "3", "--", "echo", "{i}"]
    assert main(argv) == 0
    assert capsys.readouterr().out == f"{job_id}\n"
    script = tmp / "usub-logs" / f"echo.{job_id}.script"  # named after the id the scheduler returned
    assert script.read_text() == (tmp / f"{program}.stdin").read_text()  # script fed on stdin
    assert (tmp / f"{program}.args").read_text().strip() == ""  # no script argument
    assert [p.name for p in (tmp / "usub-logs").iterdir()] == [script.name]

def test_submit_merged_single_job_keeps_no_script_file(fake_schedulers, capsys):
    tmp = fake_schedulers
    assert main(["r", "-s", "-b", "slurm", "--cwd", str(tmp), "-o", "logs", "--merge-logs", "--", "true"]) == 0
    assert not list((tmp / "logs").glob("*.script"))
    assert "cat <<'SCRIPT'" in (tmp / "sbatch.stdin").read_text()

def test_submit_failure(tmp_path, capsys, monkeypatch):
    bindir = tmp_path / "bin"
    bindir.mkdir()
    (bindir / "bsub").write_text("#!/bin/bash\necho 'Bad queue' >&2\nexit 255\n")
    (bindir / "bsub").chmod(0o755)
    monkeypatch.setenv("PATH", str(bindir))
    assert main(["r", "-s", "-b", "lsf", "--cwd", str(tmp_path), "-o", "logs", "--", "true"]) == 2
    err = capsys.readouterr().err
    assert "bsub failed (exit 255): Bad queue" in err
    (saved,) = (tmp_path / "logs").glob("true.failed-*.script")  # kept for debugging
    assert f"script: {saved}" in err

def test_merge_logs_flag_overrides_config(tmp_path, capsys):
    (tmp_path / ".usub.toml").write_text("[defaults]\nmerge_logs = true\n")
    base = ["r", "-b", "slurm", "--cwd", str(tmp_path), "--emit", "cmd"]
    assert main([*base, "--", "true"]) == 0
    assert "--error" not in capsys.readouterr().out
    assert main([*base, "--no-merge-logs", "--", "true"]) == 0
    assert "--error=" in capsys.readouterr().out

def test_local_end_to_end(tmp_path, capsys):
    for n in ("one", "two words"):
        (tmp_path / f"{n}.txt").write_text("a\nb\n")
    (tmp_path / "commands.txt").write_text(
        "wc -l < one.txt > one.count\nwc -l < 'two words.txt' > 'two words.count'\n")
    argv = ["r", "-s", "-b", "local", "-j", "2", "--cwd", str(tmp_path), "-o", "usub-logs",
            "-C", str(tmp_path / "commands.txt")]
    assert main(argv) == 0
    assert (tmp_path / "one.count").read_text().strip() == "2"
    assert (tmp_path / "two words.count").read_text().strip() == "2"
    logs = sorted(p.name for p in (tmp_path / "usub-logs").iterdir())
    assert logs == [f"commands.{x}" for x in ("1", "1.err", "2", "2.err", "script")]
    assert all((tmp_path / "usub-logs" / n).read_text() == "" for n in ("commands.1", "commands.1.err"))

def test_local_file_list_end_to_end(tmp_path, capsys):
    for n in ("one", "two words"):
        (tmp_path / f"{n}.txt").write_text("a\nb\n")
    (tmp_path / "files.txt").write_text("one.txt\ntwo words.txt\n")
    argv = ["r", "-s", "-b", "local", "-j", "2", "--cwd", str(tmp_path), "-o", "usub-logs",
            "-F", str(tmp_path / "files.txt"), "--", "wc -l < {} > {/.}.count"]
    assert main(argv) == 0
    assert (tmp_path / "one.count").read_text().strip() == "2"
    assert (tmp_path / "two words.count").read_text().strip() == "2"
    assert sorted(p.name for p in (tmp_path / "usub-logs").iterdir()) == [
        f"wc.{x}" for x in ("1", "1.err", "2", "2.err", "script")]

def test_local_merged_logs(tmp_path, capsys):
    argv = ["r", "-s", "-b", "local", "--cwd", str(tmp_path), "-o", "logs", "--merge-logs", "-a", "2",
            "--", "echo out {i}; echo err {i} >&2"]
    assert main(argv) == 0
    assert sorted(p.name for p in (tmp_path / "logs").iterdir()) == [
        "echo.1", "echo.2", "echo.script"]  # one script, one log per index
    assert sorted((tmp_path / "logs" / "echo.2").read_text().splitlines()) == ["err 2", "out 2"]

